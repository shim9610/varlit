//! Field views of variable records: where each field's value sits, so a
//! caller reads a large field into its own buffer (a buffer at a time)
//! instead of the library decoding the record whole.
//!
//! A variable payload is a run of fields, each a 16-byte header (id, wire
//! type, flags, value length) and the encoded value. A view walks the headers
//! only, through the checked record read (`record_read`), and records a
//! [`FieldSpan`] per field: the value's logical offset and length, and the
//! value itself when it is at most [`FIELD_INLINE`] bytes (a scalar), so
//! small fields cost no further read.

use super::record_read::{ChunkCache, fill_range, fill_record};
use super::*;

/// Field values up to this many bytes are carried inside their span.
pub const FIELD_INLINE: usize = 16;
const FIELD_HEADER_LEN: u64 = 16;

/// Where one field's encoded value sits in a record's logical payload.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FieldSpan {
    offset: u64,
    len: u64,
    wire: WireType,
    endian: Endian,
    /// The value's first `carried` bytes.
    inline: [u8; FIELD_INLINE],
    carried: u8,
}

impl FieldSpan {
    /// The value's logical offset in the record.
    pub const fn offset(&self) -> u64 {
        self.offset
    }
    /// The encoded value's length in bytes.
    pub const fn len(&self) -> u64 {
        self.len
    }
    pub const fn is_empty(&self) -> bool {
        self.len == 0
    }
    pub const fn wire_type(&self) -> WireType {
        self.wire
    }
    /// The value's bytes, when it is short enough to be carried here.
    pub fn inline_bytes(&self) -> Option<&[u8]> {
        (u64::from(self.carried) == self.len).then(|| &self.inline[..self.len as usize])
    }

    /// The raw data of a length-prefixed value, past its 8-byte prefix: the
    /// bytes of a `Vec<u8>`, the UTF-8 of a `String`, or the packed elements
    /// of a sequence (a `Vec<u16>` is its elements back to back, in the
    /// record's byte order). Read it with `read_span_into` into your own
    /// buffer. A byte or string prefix must name exactly the rest.
    pub fn data(&self) -> Result<FieldSpan> {
        if !matches!(
            self.wire,
            WireType::Bytes | WireType::String | WireType::Seq
        ) {
            return Err(Error::InvalidCanonicalEncoding(
                "only byte, string and sequence fields have raw data",
            ));
        }
        if self.len < 8 {
            return Err(Error::UnexpectedEof);
        }
        let prefix: [u8; 8] = self.inline[..8].try_into().expect("eight");
        let declared = match self.endian {
            Endian::Little => u64::from_le_bytes(prefix),
            Endian::Big => u64::from_be_bytes(prefix),
        };
        let rest = self.len - 8;
        let consistent = match self.wire {
            WireType::Bytes | WireType::String => declared == rest,
            // A count: each element takes at least one byte.
            _ => declared <= rest,
        };
        if !consistent {
            return Err(Error::InvalidCanonicalEncoding(
                "field length prefix disagrees with its span",
            ));
        }
        let mut inline = [0u8; FIELD_INLINE];
        let carried = usize::from(self.carried) - 8;
        inline[..carried].copy_from_slice(&self.inline[8..8 + carried]);
        Ok(FieldSpan {
            offset: self.offset + 8,
            len: rest,
            wire: WireType::Bytes,
            endian: self.endian,
            inline,
            carried: carried as u8,
        })
    }
}

/// The view of a variable block: generated by `#[derive(VarlitBlock)]` as
/// `<Block>View`, one [`FieldSpan`] per field (`Option` for a field with a
/// default).
pub trait VarlitView: VarlitBlock {
    type View;
    /// Builds the view from a walk over the record's fields. Not called
    /// directly: see [`VarlitFile::view_block`].
    #[doc(hidden)]
    fn view_from_fields(walk: FieldWalk<'_>) -> Result<Self::View>;
}

/// Runs a visitor over every field of one record: `(field id, span)`.
pub type FieldWalk<'a> =
    &'a mut dyn FnMut(&mut dyn FnMut(u32, FieldSpan) -> Result<()>) -> Result<()>;

/// The error a view reports for a field whose wire type is not its type's.
#[doc(hidden)]
pub fn view_wire_mismatch(field: &'static str, expected: WireType, actual: WireType) -> Error {
    Error::WireTypeMismatch {
        field,
        expected,
        actual,
    }
}

fn duplicate_field() -> Error {
    Error::InvalidCanonicalEncoding("duplicate variable field")
}

/// Sets a view slot, refusing a second value for the same field.
#[doc(hidden)]
pub fn view_set(slot: &mut Option<FieldSpan>, span: FieldSpan) -> Result<()> {
    if slot.replace(span).is_some() {
        return Err(duplicate_field());
    }
    Ok(())
}

/// Calls `visit` with every field of `entry`, reading only field headers
/// (and values of at most [`FIELD_INLINE`] bytes).
pub(crate) fn walk_fields(
    spec: FormatSpec,
    snapshot: &SnapshotFile,
    entry: &RecordIndexEntry,
    endian: Endian,
    cache: &std::cell::RefCell<ChunkCache>,
    visit: &mut dyn FnMut(u32, FieldSpan) -> Result<()>,
) -> Result<()> {
    let mut position = 0u64;
    let mut header = [0u8; FIELD_HEADER_LEN as usize];
    loop {
        let page = fill_record(spec, snapshot, entry, position, &mut header, cache)?;
        let total = page.end;
        if page.filled == 0 && position == total {
            return Ok(());
        }
        if page.filled != header.len() {
            return Err(Error::UnexpectedEof);
        }
        let u32_at = |at: usize| {
            let bytes: [u8; 4] = header[at..at + 4].try_into().expect("four");
            match endian {
                Endian::Little => u32::from_le_bytes(bytes),
                Endian::Big => u32::from_be_bytes(bytes),
            }
        };
        let u16_at = |at: usize| {
            let bytes: [u8; 2] = header[at..at + 2].try_into().expect("two");
            match endian {
                Endian::Little => u16::from_le_bytes(bytes),
                Endian::Big => u16::from_be_bytes(bytes),
            }
        };
        let len = {
            let bytes: [u8; 8] = header[8..16].try_into().expect("eight");
            match endian {
                Endian::Little => u64::from_le_bytes(bytes),
                Endian::Big => u64::from_be_bytes(bytes),
            }
        };
        let field_id = u32_at(0);
        let wire = u16_at(4);
        if field_id == 0 {
            return Err(Error::InvalidCanonicalEncoding(
                "variable field id must be nonzero",
            ));
        }
        if u16_at(6) != 0 {
            return Err(Error::InvalidCanonicalEncoding(
                "variable field flags must be zero",
            ));
        }
        let wire = WireType::from_u16(wire).ok_or(Error::UnknownWireType(wire))?;
        let value_at = position + FIELD_HEADER_LEN;
        let value_end = value_at
            .checked_add(len)
            .filter(|end| *end <= total)
            .ok_or(Error::UnexpectedEof)?;
        let mut span = FieldSpan {
            offset: value_at,
            len,
            wire,
            endian,
            inline: [0; FIELD_INLINE],
            carried: 0,
        };
        // The value's first bytes come along: all of a short value, the
        // length prefix of a long one.
        let head = len.min(FIELD_INLINE as u64) as usize;
        if head > 0 {
            let page = fill_record(
                spec,
                snapshot,
                entry,
                value_at,
                &mut span.inline[..head],
                cache,
            )?;
            if page.filled != head {
                return Err(Error::UnexpectedEof);
            }
            span.carried = head as u8;
        }
        visit(field_id, span)?;
        position = value_end;
    }
}

/// The checks a view or a field read makes on the entry it is given.
fn check_view_entry<T: VarlitBlock>(spec: FormatSpec, entry: &RecordIndexEntry) -> Result<()> {
    crate::collections::ensure_registered_block::<T>(spec)?;
    if T::KIND != BlockKind::Variable {
        return Err(Error::InvalidFormatSpec(
            "field views are for variable blocks",
        ));
    }
    if entry.block_id != T::ID {
        return Err(Error::UnregisteredBlock(entry.block_id));
    }
    if entry.block_version != T::VERSION {
        return Err(Error::BlockVersionMismatch {
            block_id: T::ID,
            expected: T::VERSION,
            actual: entry.block_version,
        });
    }
    Ok(())
}

pub(crate) fn view_block<T: VarlitView>(
    spec: FormatSpec,
    snapshot: &SnapshotFile,
    entry: &RecordIndexEntry,
    cache: &std::cell::RefCell<ChunkCache>,
) -> Result<T::View> {
    check_view_entry::<T>(spec, entry)?;
    let endian = T::ENDIAN.unwrap_or(spec.endian);
    T::view_from_fields(&mut |visit| walk_fields(spec, snapshot, entry, endian, cache, visit))
}

pub(crate) fn read_span(
    spec: FormatSpec,
    snapshot: &SnapshotFile,
    entry: &RecordIndexEntry,
    span: FieldSpan,
    out: &mut [u8],
    cache: &std::cell::RefCell<ChunkCache>,
) -> Result<crate::RecordPage> {
    let end = span
        .offset
        .checked_add(span.len)
        .ok_or(Error::ResourceArithmeticOverflow {
            resource: "field span",
        })?;
    fill_range(spec, snapshot, entry, span.offset, end, out, cache)
}

pub(crate) fn decode_field<F: crate::VarlitDecode>(
    spec: FormatSpec,
    snapshot: &SnapshotFile,
    entry: &RecordIndexEntry,
    span: FieldSpan,
    cache: &std::cell::RefCell<ChunkCache>,
) -> Result<F> {
    if span.wire != F::WIRE_TYPE {
        return Err(view_wire_mismatch("field", F::WIRE_TYPE, span.wire));
    }
    let limit = spec
        .read_limits
        .require(ReadLimitKey::MaterializedBytes)?
        .unwrap_or(u64::MAX);
    if let Some(bytes) = span.inline_bytes() {
        return crate::codec::Decoder::decode_from_slice_limited(bytes, span.endian, limit);
    }
    // A field read whole must be small: a large one is read with
    // `read_span_into` into the caller's buffer.
    if span.len > record_chunks::CHUNK_LEN {
        return Err(Error::LimitExceeded {
            resource: "field decoded whole (read it with read_span_into)",
            actual: span.len,
            limit: record_chunks::CHUNK_LEN,
        });
    }
    spec.read_limits
        .check(ReadLimitKey::MaterializedBytes, span.len)?;
    // Staged in the handle's scratch, not a buffer made for this call.
    let mut bytes = lend_scratch(cache);
    let decoded = (|| {
        let len = span.len as usize;
        if bytes.len() < len {
            bytes
                .try_reserve_exact(len - bytes.len())
                .map_err(|_| Error::AllocationFailed {
                    resource: "field value",
                    requested: span.len,
                })?;
            bytes.resize(len, 0);
        }
        let page = read_span(spec, snapshot, entry, span, &mut bytes[..len], cache)?;
        if page.filled != len {
            return Err(Error::UnexpectedEof);
        }
        crate::codec::Decoder::decode_from_slice_limited(
            &bytes[..len],
            span.endian,
            limit - span.len,
        )
    })();
    return_scratch(cache, bytes);
    decoded
}

impl VarlitFile {
    /// Where each field of a variable record sits, without reading the
    /// fields' values (values of at most [`FIELD_INLINE`] bytes come along).
    /// Read a large field with [`Self::read_span_into`] into a buffer of
    /// your own; decode a small one with [`Self::decode_field`].
    pub fn view_block<T: VarlitView>(&self, entry: &RecordIndexEntry) -> Result<T::View> {
        view_block::<T>(self.spec, &self.snapshot, entry, &self.record_cache)
    }

    /// Reads a field's encoded value into `out`, as much as it holds; continue
    /// with [`Self::read_record_from`] while the page names a next cursor.
    /// Checked bytes only, as [`Self::read_record_into`].
    pub fn read_span_into(
        &self,
        entry: &RecordIndexEntry,
        span: FieldSpan,
        out: &mut [u8],
    ) -> Result<crate::RecordPage> {
        read_span(
            self.spec,
            &self.snapshot,
            entry,
            span,
            out,
            &self.record_cache,
        )
    }

    /// Decodes one small field (at most 64 KiB encoded) of the record.
    pub fn decode_field<F: crate::VarlitDecode>(
        &self,
        entry: &RecordIndexEntry,
        span: FieldSpan,
    ) -> Result<F> {
        decode_field(self.spec, &self.snapshot, entry, span, &self.record_cache)
    }
}
